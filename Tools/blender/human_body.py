"""
The game's human body, generated by MPFB (MakeHuman for Blender): a rigged man about 1.80 m tall on a Unity-friendly skeleton.
Its base mesh and targets are CC0 (https://static.makehumancommunity.org/about/license.html). The add-on stays in Blender;
only the generated body comes into the project.

    ~/Programs/blender/blender --background --python Tools/blender/human_body.py -- OUT_DIR [--name NAME] [--rig mixamo_unity]

Writes OUT_DIR/NAME.fbx, OUT_DIR/NAME_front.png, OUT_DIR/NAME_side.png and prints a "[human]" report: height, bones, triangles.
"""
import json
import math
import os
import sys

import bpy
from mathutils import Vector

argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
out = os.path.abspath(argv[0]) if argv else os.getcwd()
def opt(name, default):
    return argv[argv.index(name) + 1] if name in argv else default
NAME = opt("--name", "Human_Male")
RIG = opt("--rig", "mixamo_unity")
TARGET_HEIGHT = float(opt("--height", "1.80"))
os.makedirs(out, exist_ok=True)

# Blender's own start-up objects out.
for o in list(bpy.data.objects):
    bpy.data.objects.remove(o, do_unlink=True)

import addon_utils
addon_utils.enable("bl_ext.blender_org.mpfb", default_set=False)
from bl_ext.blender_org.mpfb.services.humanservice import HumanService
from bl_ext.blender_org.mpfb.services.targetservice import TargetService

macro = TargetService.get_default_macro_info_dict()
macro.update({"gender": 1.0, "age": 0.5, "muscle": 0.62, "weight": 0.52, "proportions": 0.6, "height": 0.5})

body = HumanService.create_human(mask_helpers=True, detailed_helpers=False, extra_vertex_groups=True, feet_on_ground=True, scale=0.1, macro_detail_dict=macro)
rig = HumanService.add_builtin_rig(body, RIG, import_weights=True)
bpy.context.view_layer.update()

def world_extent(obj):
    dg = bpy.context.evaluated_depsgraph_get()
    mesh = obj.evaluated_get(dg).to_mesh()
    zs = [(obj.matrix_world @ v.co).z for v in mesh.vertices]
    tris = sum(len(p.vertices) - 2 for p in mesh.polygons)
    obj.evaluated_get(dg).to_mesh_clear()
    return min(zs), max(zs), tris

low, high, tris = world_extent(body)
height = high - low
print(f"[human] generated: height {height:.3f} m (feet {low:.3f}), triangles shown {tris}, bones {len(rig.data.bones)}")
print("[human] bones:", ", ".join(b.name for b in rig.data.bones)[:900])

# Exactly the wanted height, with the scale applied so Unity sees a body in metres at scale 1.
k = TARGET_HEIGHT / height
rig.scale = rig.scale * k
bpy.context.view_layer.update()
bpy.ops.object.select_all(action="DESELECT")
rig.select_set(True)
bpy.context.view_layer.objects.active = rig
bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
low, high, tris = world_extent(body)
print(f"[human] scaled: height {high - low:.3f} m, armature scale {tuple(round(x, 3) for x in rig.scale)}")

# Two looks at it.
bpy.context.scene.render.engine = "BLENDER_WORKBENCH"
bpy.context.scene.display.shading.light = "STUDIO"
bpy.context.scene.display.shading.color_type = "SINGLE"
bpy.context.scene.display.shading.single_color = (0.75, 0.62, 0.52)
bpy.context.scene.render.resolution_x, bpy.context.scene.render.resolution_y = 500, 900
cam = bpy.data.objects.new("Cam", bpy.data.cameras.new("Cam"))
bpy.context.collection.objects.link(cam)
bpy.context.scene.camera = cam
cam.data.type = "ORTHO"
cam.data.ortho_scale = TARGET_HEIGHT * 1.1
for label, at, rot in (("front", (0, -4, TARGET_HEIGHT / 2), (math.pi / 2, 0, 0)), ("side", (4, 0, TARGET_HEIGHT / 2), (math.pi / 2, 0, math.pi / 2))):
    cam.location, cam.rotation_euler = at, rot
    bpy.context.scene.render.filepath = os.path.join(out, f"{NAME}_{label}.png")
    try:
        bpy.ops.render.render(write_still=True)
        print(f"[human] wrote {NAME}_{label}.png")
    except Exception as e:
        print(f"[human] no render ({e}); FBX only")
        break
bpy.data.objects.remove(cam, do_unlink=True)

# The FBX Unity imports: armature and body only, helpers left out by the mask (applied), no leaf bones, +Y up.
bpy.ops.object.select_all(action="DESELECT")
body.select_set(True)
rig.select_set(True)
bpy.context.view_layer.objects.active = rig
bpy.ops.export_scene.fbx(
    filepath=os.path.join(out, f"{NAME}.fbx"), use_selection=True, object_types={"ARMATURE", "MESH"},
    use_mesh_modifiers=True, add_leaf_bones=False, bake_anim=False, axis_forward="-Z", axis_up="Y",
    apply_unit_scale=True, apply_scale_options="FBX_SCALE_ALL", mesh_smooth_type="FACE")
print(f"[human] wrote {NAME}.fbx, {os.path.getsize(os.path.join(out, NAME + '.fbx')) // 1024} KB, triangles {tris}")
print("[human] report " + json.dumps({"height": round(high - low, 3), "triangles": tris, "bones": len(rig.data.bones), "rig": RIG}))
