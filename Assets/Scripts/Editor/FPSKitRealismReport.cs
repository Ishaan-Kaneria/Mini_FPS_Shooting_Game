using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using UnityEngine;

namespace FPSKit.EditorTools
{
    /// <summary>The realism audit's report and CSV (FPSKitRealismAudit).</summary>
    public static partial class FPSKitRealismAudit
    {
        static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

        static string Csv(string s) => s == null ? "" : s.Contains(',') || s.Contains('"') || s.Contains('\n') ? "\"" + s.Replace("\"", "\"\"") + "\"" : s;

        static string F(double v, string f = "0.###") => v.ToString(f, Inv);

        static string Maps(MatInfo m) =>
            string.Join("+", new[] { m.baseMap != null ? "albedo" : null, m.normalMap != null ? "normal" : null, m.maskMap != null ? "mask" : null,
                                     m.aoMap != null ? "ao" : null, m.detailAlbedo != null || m.detailNormal != null ? "detail" : null,
                                     m.emissive ? "emission" : null }.Where(x => x != null).DefaultIfEmpty("none"));

        static void WriteCsv(List<Item> ranked)
        {
            var sb = new StringBuilder();
            sb.AppendLine("rank,object,source,group,kind,instances,triangles,area_m2,tris_per_m2,bevelled_share,axis_aligned_share,plain_box_share,open_edge_m,thickness_median_m,shell_share," +
                          "shader,maps,texture_px,texel_per_m,repeats,albedo_mean,albedo_p2,albedo_p98,albedo_variation,albedo_fine_variation,smoothness,metallic,normal_tilt_deg," +
                          "screen_pct,views_seen,nearest_m,shape,surface,light,overall,reasons,measured,asset");
            int rank = 0;
            foreach (var it in ranked)
            {
                rank++;
                var m = it.mats.OrderByDescending(x => x.mat != null && it.matArea.TryGetValue(x.mat, out var a) ? a : 0).FirstOrDefault() ?? new MatInfo { shader = "" };
                var th = it.thickness.OrderBy(x => x).ToList();
                sb.AppendLine(string.Join(",", new[]
                {
                    rank.ToString(Inv), Csv(it.name), Csv(it.source), Csv(it.group), Csv(it.cls), it.Instances.ToString(Inv), it.tris.ToString(Inv), F(it.area, "0.0"),
                    F(it.TrisPerM2, "0.0"), F(it.BevelShare), F(it.AxisShare), F(it.BoxShare), F(it.openLen, "0.0"),
                    th.Count > 0 ? F(th[th.Count / 2]) : "", it.thickSamples > 0 ? F(it.shellSamples / it.thickSamples) : "",
                    Csv(string.Join(" | ", it.mats.Select(x => x.shader).Distinct())), Csv(string.Join(" | ", it.mats.Select(Maps).Distinct())),
                    m.baseMap != null ? $"{m.baseMap.width}x{m.baseMap.height}" : "", F(it.Texel, "0"), F(it.repeatsP95, "0.0"),
                    F(m.AlbedoMean), F(m.AlbedoP2), F(m.AlbedoP98), F(m.Variation), F(m.Fine), F(m.smoothness), F(m.metallic), F(m.Tilt, "0.0"),
                    F(it.importance, "0.0000"), it.views.ToString(Inv), it.minDist < float.MaxValue ? F(it.minDist, "0.0") : "",
                    Label(it.shape), Label(it.surface), Label(it.light), Label(it.overall),
                    Csv(string.Join(" ; ", it.reasons)), Csv(string.Join(" ; ", it.measured)), Csv(it.assetPath),
                }));
            }
            Directory.CreateDirectory("Docs");
            File.WriteAllText($"Docs/REALISM_AUDIT_{_arena}.csv", sb.ToString());
        }

        static void WriteReport(string theme, string scenePath, List<Item> ranked, List<Item> chosen, List<View> route)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"# Realism audit: {theme}");
            sb.AppendLine();
            sb.AppendLine($"Generated by `FPSKitRealismAudit` (FPSKit > Realism > Audit Arena, or `UNITY_GRAPHICS=1 Tools/unity-batch.sh FPSKitBatch.AuditRealism -fpskitTheme \"{theme}\"`) " +
                          $"on {DateTime.Now:yyyy-MM-dd HH:mm} from `{scenePath}` at the **{QualitySettings.names[QualitySettings.GetQualityLevel()]}** tier. Do not edit by hand: it is rewritten on every run. " +
                          $"Every row of `Docs/REALISM_AUDIT_{_arena}.csv` is one object; the images are in `Build/Realism/{_arena}/` (not in git).");
            sb.AppendLine();
            sb.AppendLine("## How it measures");
            sb.AppendLine();
            sb.AppendLine("An object is real only if its **shape**, its **surface** and its **response to light** all pass. Each is measured, never judged from a screenshot.");
            sb.AppendLine();
            sb.AppendLine($"* **Objects**: every imported model (by prefab), every generated surface (the builder's group and material: the town is merged into chunk meshes, and a fix is made per material in the generator), Unity primitives, each terrain layer, the sky, and each gun's first-person model.");
            sb.AppendLine($"* **Screen importance**: a fixed walk of {RouteLength:0} m ({route.Count(v => !v.indoors)} views, every 5 m looking ahead and 70 degrees to each side, plus {route.Count(v => v.indoors)} views across the rooms of the houses nearest it), each drawn once with every object in its own id colour and its pixels counted. `screen %` is the object's mean share of the screen over all views; `near` means the walk passes within {NearMetres} m of it or it fills a tenth of a view.");
            sb.AppendLine("* **Shape**: triangles; triangles per m2; bevelled share of the hard-edge length (a 10-60 degree edge beside a strip under 6 cm wide; 60 degrees and over is a hard edge); the share of the surface in plain boxes (8 corners, 12 triangles); wall thickness by casts from behind the face (a shell meets nothing within 1 m).");
            sb.AppendLine("* **Surface**: maps present, texture size, texels per metre (UV area against world area), how often one texture repeats across a face (95th percentile of a triangle's UV span), albedo variation (std/mean of luminance over the texture's full-size texels), the normal map's mean tilt with its strength applied.");
            sb.AppendLine("* **Light**: lit shader, shadows received, light probes used by moving renderers, albedo against URP's own validation range (0.01-0.90) and against the real material's range, smoothness against the real material's, metallic only on bare metal, an occlusion map where it is smooth, emission only on lamps. For the objects with evidence, the five-light stage test is measured too (below).");
            sb.AppendLine();
            sb.AppendLine("### Thresholds");
            sb.AppendLine();
            sb.AppendLine("| Rule | Verdict |");
            sb.AppendLine("|---|---|");
            sb.AppendLine($"| Unity primitive, near / far | FAKE / NEEDS WORK |");
            sb.AppendLine($"| a single plain box, or {BoxShareFake:P0}+ of a near prop in plain boxes | FAKE |");
            sb.AppendLine($"| 25%+ of the surface in plain boxes | NEEDS WORK |");
            sb.AppendLine($"| edges: under {BevelShareMin:P0} of hard-edge length bevelled | NEEDS WORK |");
            sb.AppendLine($"| near prop under {PropTrisPerM2Min} triangles per m2 | NEEDS WORK |");
            sb.AppendLine($"| wall surface: 60%+ of casts through it meet no back within 1 m | NEEDS WORK |");
            sb.AppendLine($"| flat single colour: albedo variation under {FlatVariation} and no normal map | FAKE |");
            sb.AppendLine($"| flat colour blocks: a palette texture (variation inside any 4 x 4 patch of samples under {FineVariationMin}) and no normal map | FAKE |");
            sb.AppendLine($"| a held gun under {HeldTrisMin:N0} triangles | NEEDS WORK |");
            sb.AppendLine($"| no normal map on a near surface; normal map mean tilt under {NormalTiltMin} degrees; no albedo texture | NEEDS WORK |");
            sb.AppendLine($"| texels per metre under {TexelNear} when near, under {TexelFar} anywhere | NEEDS WORK |");
            sb.AppendLine($"| one texture repeating {RepeatsMax}+ times across a face with no detail map or vertex colour | NEEDS WORK |");
            sb.AppendLine($"| unlit shader; emission on anything but a lamp; renderers not receiving shadows (near) | FAKE |");
            sb.AppendLine($"| albedo outside URP's validation range ({AlbedoValidMin}-{AlbedoValidMax}) or the real material's; smoothness outside the real material's; metallic on a non-metal; smooth (0.5+) with no occlusion map; moving renderers with no light probes | NEEDS WORK |");
            sb.AppendLine($"| material kind not recognised from its name | UNCERTAIN (shown, never assumed fine) |");
            sb.AppendLine($"| light test: brighter against the grey card at night than at midday by 2.5x | FAKE |");
            sb.AppendLine($"| light test: with every light off it keeps over 2% of its midday brightness (it emits) | FAKE |");
            sb.AppendLine($"| light test: brightness varying under 6% across it in raking light; URP's albedo check flagging over 10% of it | NEEDS WORK |");
            sb.AppendLine($"| light test in shade, indoors, at night | reported against the grey card, not rated (a surface shaded at midday keeps all of it in shade) |");
            sb.AppendLine($"| a material on under {MinorShare:P0} of an object | at worst NEEDS WORK |");
            sb.AppendLine();
            sb.AppendLine("Real material ranges used (linear albedo, smoothness):");
            sb.AppendLine();
            sb.AppendLine("| Kind | Albedo | Smoothness | Metallic |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var c in Classes) sb.AppendLine($"| {c.cls} | {(c.cls is "glass" or "water" ? "-" : $"{c.aMin:0.00}-{c.aMax:0.00}")} | {c.sMin:0.00}-{c.sMax:0.00} | {(c.metal ? "yes" : "no")} |");
            sb.AppendLine();

            sb.AppendLine("## Summary");
            sb.AppendLine();
            // The world's share (the guns are alternatives, one held at a time: they are counted apart).
            var worldItems = ranked.Where(i => i.source != "player weapon").ToList();
            double screen = worldItems.Sum(i => i.importance);
            sb.AppendLine("| Verdict | Objects of the world | Share of the world the player sees | Weapons (guns and arms) |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var v in new[] { Verdict.Real, Verdict.Uncertain, Verdict.NeedsWork, Verdict.Fake })
            {
                var of = worldItems.Where(i => i.overall == v).ToList();
                sb.AppendLine($"| {Label(v)} | {of.Count} | {(screen > 0 ? of.Sum(i => i.importance) / screen : 0):P0} | {ranked.Count(i => i.source == "player weapon" && i.overall == v)} |");
            }
            sb.AppendLine();
            sb.AppendLine($"Objects nothing on the walk sees (they stand away from it) have a screen share of 0 and are rated all the same.");
            sb.AppendLine();
            sb.AppendLine($"The most seen objects of the world that fail, then the guns and the arms (one gun is held at a time; its share is while held), with evidence (close-up, wireframe, texel density, URP albedo check, five-light test) in `Build/Realism/{_arena}/<object>/`:");
            sb.AppendLine();
            sb.AppendLine("| # | Object | Source | Screen % | Near | Shape | Surface | Light | Verdict |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|");
            int n = 0;
            foreach (var it in chosen)
            {
                if (n > 0 && it.source == "player weapon" && chosen[n - 1].source != "player weapon") sb.AppendLine("| | **Weapons** | | | | | | | |");
                sb.AppendLine($"| {++n} | {it.name} | {it.source} | {it.importance:0.00} | {(it.minDist < NearMetres ? $"{it.minDist:0.0} m" : "no")} | {Label(it.shape)} | {Label(it.surface)} | {Label(it.light)} | **{Label(it.overall)}** |");
            }
            sb.AppendLine();

            n = 0;
            foreach (var it in chosen)
            {
                sb.AppendLine($"### {++n}. {it.name}: {Label(it.overall)}");
                sb.AppendLine();
                sb.AppendLine($"{it.source}, group {it.group}, kind *{it.cls}*, {it.Instances} instance(s), `{it.assetPath}`. Screen {it.importance:0.00}% (seen in {it.views} views), nearest {(it.minDist < float.MaxValue ? $"{it.minDist:0.0} m" : "-")}.");
                sb.AppendLine();
                sb.AppendLine($"* Shape ({Label(it.shape)}): {it.tris:N0} triangles over {it.area:0.0} m2 ({it.TrisPerM2:0.0}/m2), {it.BevelShare:P1} of hard-edge length bevelled, {it.AxisShare:P0} of the surface axis-aligned, {it.BoxShare:P0} plain boxes" +
                              (it.thickSamples > 0 ? $", thickness {(it.thickness.Count > 0 ? $"{it.thickness.OrderBy(x => x).ElementAt(it.thickness.Count / 2):0.00} m median" : "none found")} ({it.shellSamples:0} of {it.thickSamples:0} casts met no back)" : "") + ".");
                foreach (var m in it.mats)
                    sb.AppendLine($"* Material `{(m.mat != null ? m.mat.name : it.name)}` ({m.cls}): `{m.shader}`, maps {Maps(m)}" +
                                  (m.baseMap != null ? $", {m.baseMap.width}x{m.baseMap.height}" : "") +
                                  $", albedo mean {m.AlbedoMean:0.00} (2-98%: {m.AlbedoP2:0.00}-{m.AlbedoP98:0.00}, variation {m.Variation:0.000}, in small patches {m.Fine:0.000}), smoothness {m.smoothness:0.00}, metallic {m.metallic:0.00}" +
                                  (m.normalMap != null ? $", normal tilt {m.Tilt:0.0} deg (strength {m.bumpScale:0.00})" : "") + (m.emissive ? $", emission {m.emissionLum:0.00}" : "") + ".");
                if (it.texelArea > 0) sb.AppendLine($"* Surface: {it.Texel:0} texels per metre, repeats {it.repeatsP95:0.0}x across a face, vertex colour variation {(it.vertexColourVariation ? "yes" : "no")}.");
                foreach (var r in it.reasons) sb.AppendLine($"* {r}");
                foreach (var m in it.measured.Where(x => !x.StartsWith("!"))) sb.AppendLine($"* Measured: {m}");
                if (it.evidence != null)
                    sb.AppendLine($"* Evidence: `{it.evidence}/` close.png, wire.png, texel.png, albedo_check.png, light_test.jpg (left to right: midday, evening, shade, indoor through a doorway, night under a lamp).");
                sb.AppendLine();
            }

            sb.AppendLine("## Every other object that is not REAL (by screen share)");
            sb.AppendLine();
            sb.AppendLine("| Object | Source | Screen % | Verdict | Why |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (var it in ranked.Where(i => i.overall != Verdict.Real && !chosen.Contains(i)).Take(150))
                sb.AppendLine($"| {it.name} | {it.source} | {it.importance:0.000} | {Label(it.overall)} | {string.Join("; ", it.reasons.Take(3)).Replace("|", "/")} |");
            sb.AppendLine();
            sb.AppendLine("## Run log");
            sb.AppendLine();
            sb.AppendLine("```");
            sb.Append(_log);
            sb.AppendLine("```");
            File.WriteAllText($"Docs/REALISM_AUDIT_{_arena}.md", sb.ToString());
        }
    }
}
